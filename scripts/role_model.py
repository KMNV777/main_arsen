def _tbl(head: List[str], rows: List[List[str]]) -> str:
    h = "".join(f"<th>{e(x)}</th>" for x in head)
    b = "".join("<tr>" + "".join(f"<td>{e(c)}</td>" for c in r) + "</tr>" for r in rows)
    return f'<div class="tw"><table class="confluenceTable"><tbody><tr>{h}</tr>{b}</tbody></table></div>'


def mapping_html() -> str:
    return _tbl(["Роль процесса", "Кто", "Карточка ролевой модели", "Что применяем в релизе", "Шаги"],
                [[c, n, card, use, steps] for c, n, card, use, steps in MAPPING])


def decisions_html() -> str:
    return _tbl(["Решение", "Кто решает", "Основание в карточке", "Где применяется"], [list(x) for x in DECISIONS])


def drafts_html() -> str:
    out = []
    for d in DRAFTS:
        lis = lambda xs: "<ul>" + "".join(f"<li>{e(x)}</li>" for x in xs) + "</ul>"
        out.append(f"<h3>{e(str(d['role']))}</h3><p><b>Цель роли:</b> {e(str(d['goal']))}</p>"
                   f"<p><b>Ключевые задачи</b></p>{lis(d['tasks'])}<p><b>Полномочия</b></p>{lis(d['auth'])}"
                   f"<p><b>Ключевые результаты / KPI</b></p>{lis(d['kpi'])}"
                   f"<p><b>Клиенты:</b> {e(str(d['clients']))}. <b>Партнёры:</b> {e(str(d['partners']))}.</p>")
    return "".join(out)


