    # -- вспомогательные
    NW, NH = 150, 62
    cyl = {
        "RM": top["RM"] + 70, "QA": top["QA"] + 70, "DEVa": top["DEV"] + 55, "DEVb": top["DEV"] + 165,
        "ИБa": top["ИБ"] + 50, "ИБb": top["ИБ"] + 140, "DBA": top["DBA"] + 70,
    }
    nodes: Dict[str, Cell] = {}

    def step(sid: str, x: float, row: str, track: str = "") -> Cell:
        _, ph, name, role, kind, _, _, _, new = SID[sid]
        lane = {"RM": "RM", "QA": "QA", "DEV": "DEV", "ИБ": "ИБ", "DBA": "DBA", "OPS": "DBA"}[role]
        role_ln = role + (f" · трек {track}" if track else "") + ("  ★нов." if new else "")
        fill = "#FFF2CC" if kind == "par" else "#FFFFFF"
        stroke = ORANGE if new else C_STROKE[role]
        c = p.add("round", x, cyl[row] - NH / 2, NW, NH, [(f"{sid}  {name}", "b"), (role_ln, "s")],
                  id=f"s{sid}", fill=fill, stroke=stroke, sw=2.2 if new else 1.2, dash=(kind == "opt"), fs=11,
                  tooltip="; ".join(["Вход: " + SID[sid][5], "Выход: " + SID[sid][6]]))
        nodes[sid] = c
        return c

    def gate(sid: str, cx: float, cy: float, w: float, h: float, label: str) -> Cell:
        new = SID[sid][8]
        c = p.add("diamond", cx - w / 2, cy - h / 2, w, h, [(label, "b")], id=f"s{sid}",
                  fill="#D5E8D4", stroke=ORANGE if new else GREEN, sw=2.2 if new else 1.5, fs=10)
        nodes[sid] = c
        return c

    # -- старт
    start = p.add("ellipse", 171, cyl["RM"] - 14, 28, 28, [], fill="#000000", stroke="#000000", id="start")

    # -- Ф0
