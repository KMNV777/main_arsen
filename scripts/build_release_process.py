    # -- зона параллельного блока
    zt, zb = top["QA"], top["ИБ"] + 180
    p.add("rect", 1535, zt, 790, zb - zt, [], fill="#FFF2CC", stroke=ORANGE, dash=True, sw=1.5, opacity=28)
