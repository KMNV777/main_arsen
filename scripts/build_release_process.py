    g1 = gate("G1", 2235, top["ИБ"] + 85, 120, 90, "G1 Согласование ИБ\nAND-join")
    # -- Ф3..Ф5
    n31 = step("3.1", 2350, "DEVa")
    n41 = step("4.1", 2540, "DBA")
    n42 = step("4.2", 2730, "RM")
    n43 = step("4.3", 2920, "RM")
    g2 = gate("G2", 3205, cyl["RM"], 120, 84, "G2 Go / No-Go")
    hf = p.add("round", 3130, cyl["DEVa"] - NH / 2, NW, NH,
               [("HF  Hotfix-поток", "b"), ("DEV · hotfix/* от master → повтор 2.4→G1→3.1", "s")],
               id="sHF", fill="#FFE6CC", stroke="#D79B00", sw=1.5, fs=11)
    n51 = step("5.1", 3330, "DBA")
    n52 = step("5.2", 3520, "DBA")
    n53 = step("5.3", 3710, "QA")
    n54 = step("5.4", 3900, "DEVa")
    n55 = step("5.5", 4090, "RM")
    end = p.add("ellipse", 4276, cyl["RM"] - 14, 28, 28, [], fill="#000000", stroke="#000000", id="end")

    # -- последовательные связи
    p.link(start, "R", n01, "L")
    p.link(n01, "R", n02, "L")
    p.link(n02, "R", g03, "L")
    p.link(g03, "R", n11, "T", "hv", label="далее (всегда)")
    p.link(g03, "B", n04, "T", dash=True, label="Да: трек C (ПСИ)")
    p.link(n04, "R", n05, "L", "hvh", mid=781, dash=True)
