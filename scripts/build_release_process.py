def critical_path(psi: bool, ptz: bool) -> Tuple[int, List[str]]:
    """Самая длинная цепочка по SLA от rc (1.3) до закрытия, рабочие дни."""
    skip = set() if psi else {"3.3"}
    if not ptz:
        skip.add("6.1")
    best: Dict[str, Tuple[int, List[str]]] = {}

    def f(n: str) -> Tuple[int, List[str]]:
        if n in best:
            return best[n]
        d = 0 if n in skip else SLA[n]
        pre = [f(q) for q in PRED[n] if q not in skip or True]
        base = max(pre, key=lambda t: t[0]) if pre else (0, [])
        best[n] = (base[0] + d, base[1] + ([] if n in skip else [n]))
        return best[n]

    return f("12.6")


def sla_text(sid: str) -> str:
    return "по спринту" if SLA[sid] == 0 else f"≤ {SLA[sid]} дн"

