def dur(n: int, psi: bool) -> float:
    if n in IN_SPRINT:
        return 9.0
    if n == ID["psi"]:
        return 5.0 if psi else 0.0
    return float(SN[n][6] or 0)


def schedule(psi: bool = False) -> Dict[int, Tuple[float, float]]:
    out: Dict[int, Tuple[float, float]] = {}
    for n in range(1, N_STEPS + 1):
        st = max([out[p][1] for p in PRED.get(n, [])] or [0.0])
        out[n] = (st, st + dur(n, psi))
    return out


def total_days(psi: bool) -> float:
    return max(v[1] for v in schedule(psi).values())


def sla_text(n: int) -> str:
    if n in IN_SPRINT:
        return "в течение спринта"
    if n == ID["exclude"]:
        return "в день демо"
    if n == ID["freeze"]:
        return "в последний день спринта"
    if n == ID["psi"]:
        return "0 дн. (не нужен) / до 5 дн."
    d = SN[n][6]
    return f"{int(d)} дн." if d == int(d) else f"{d} дн."


