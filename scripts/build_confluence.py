def who(role: str) -> str:
    return "; ".join(WHO.get(t.strip(), t.strip()) for t in role.split("+"))


def table(head: List[str], rows: List[List[str]], widths: List[int] | None = None) -> str:
    h = "".join(f"<th>{e(x)}</th>" for x in head)
    body = ""
    for r in rows:
        body += "<tr>" + "".join(c if c.startswith("<t") else f"<td>{e(c)}</td>" for c in r) + "</tr>"
    return f'<table class="confluenceTable"><tbody><tr>{h}</tr>{body}</tbody></table>'


def ul(items: List[str]) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


def ol(items: List[str]) -> str:
    return "<ol>" + "".join(f"<li>{i}</li>" for i in items) + "</ol>"


def steps_rows(with_who: bool = True) -> List[List[str]]:
    rows: List[List[str]] = []
    last = -1
    for sid, ref, phase, name, role, k, vin, vout, cal, errs, mark in B.STEPS:
        if phase != last:
            rows.append([f'<td colspan="9"><b>{e(B.PH_NAME[phase]) if hasattr(B, "PH_NAME") else e(PH[phase])}</b></td>'])
            last = phase
        flag = " ★" if mark == "new" else ""
        rows.append([f"<td><b>{e(sid)}</b></td>", ref, name + flag, who(role), KIND[k], B.sla_text(sid), vin, vout, cal])
    return rows


