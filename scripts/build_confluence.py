def cp_table() -> str:
    rows = []
    for name, psi, ptz in (("ПСИ + ПТЗ", True, True), ("только ПСИ", True, False), ("только ПТЗ", False, True), ("без ПСИ и ПТЗ", False, False)):
        d, path = B.critical_path(psi, ptz)
        rows.append([name, str(d), f"{d / 5:.1f}", " → ".join(path)])
    return table(["Сценарий", "Раб. дней", "Недель", "Критический путь"], rows)


def cat_map() -> str:
    rows = []
    for sid, ref, phase, name, role, k, vin, vout, cal, errs, mark in B.STEPS:
        if cal not in ("—", ""):
            rows.append([sid, name, cal, who(role.split("+")[0]), errs])
    return table(["Шаг", "Название", "Категория в «Причина сдвига и риск»", "Кто эскалирует", "Типичные коды ошибок"], rows)


